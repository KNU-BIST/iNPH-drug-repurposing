assert_equal <- function(actual, expected, label) {
  if (
    length(actual) != 1L ||
    is.na(actual) ||
    actual != expected
  ) {
    stop(
      label,
      " mismatch: expected ",
      expected,
      ", observed ",
      paste(actual, collapse = ", ")
    )
  }
  invisible(TRUE)
}

assert_close <- function(actual, expected, tolerance, label) {
  if (
    length(actual) != 1L ||
    is.na(actual) ||
    abs(actual - expected) > tolerance
  ) {
    stop(
      label,
      " mismatch: expected ",
      expected,
      " +/- ",
      tolerance,
      ", observed ",
      paste(actual, collapse = ", ")
    )
  }
  invisible(TRUE)
}

assert_true <- function(condition, label) {
  if (
    length(condition) != 1L ||
    is.na(condition) ||
    !isTRUE(condition)
  ) {
    stop(
      label,
      " failed."
    )
  }
  invisible(TRUE)
}

