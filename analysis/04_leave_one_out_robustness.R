# -----------------------------------------------------------------------------
# Section 3 . Leave-one-patient-out DESeq2 function
# -----------------------------------------------------------------------------

jaccard_similarity <- function(a, b) {
  length(intersect(a, b)) / length(union(a, b))
}

run_loo_deseq <- function(
    drop_patient,
    cell_meta,
    counts_mat,
    full_up,
    full_dn,
    top_n = TOP_N
) {

  meta_loo <- cell_meta |>
    dplyr::filter(patient != drop_patient)

  remaining_counts <- table(meta_loo$patient, meta_loo$state)

  if (
    nrow(remaining_counts) != 8L ||
    ncol(remaining_counts) != 2L ||
    any(remaining_counts < MIN_PSEUDOBULK_CELLS)
  ) {
    stop(
      "Invalid paired LOO design after dropping patient ",
      drop_patient,
      "."
    )
  }

  meta_loo$group <- paste0(
    "P", meta_loo$patient, "_", meta_loo$state
  )

  groups <- unique(meta_loo$group)

  if (length(groups) != 16L) {
    stop(
      "Expected 16 patient-by-state pseudobulks after dropping patient ",
      drop_patient,
      "; observed ",
      length(groups),
      "."
    )
  }

  pb_mat <- sapply(groups, function(g) {
    cells <- meta_loo$cell[meta_loo$group == g]
    Matrix::rowSums(counts_mat[, cells, drop = FALSE])
  })

  if (!is.matrix(pb_mat) || ncol(pb_mat) != 16L) {
    stop("Pseudobulk aggregation failed for patient ", drop_patient, ".")
  }

  pb_col <- data.frame(
    group = groups,
    patient = factor(gsub("P(\\d+)_.*", "\\1", groups)),
    state = factor(
      gsub(".*_(IFN|classical)", "\\1", groups),
      levels = c("classical", "IFN")
    ),
    row.names = groups,
    stringsAsFactors = FALSE
  )

  if (!identical(colnames(pb_mat), rownames(pb_col))) {
    stop("Pseudobulk counts and metadata are misaligned.")
  }

  design_table <- table(pb_col$patient, pb_col$state)

  if (
    nrow(design_table) != 8L ||
    ncol(design_table) != 2L ||
    any(design_table != 1L)
  ) {
    stop("DESeq2 design is not fully paired for patient ", drop_patient, ".")
  }

  dds <- DESeq2::DESeqDataSetFromMatrix(
    countData = as.matrix(pb_mat),
    colData = pb_col,
    design = ~ patient + state
  )

  dds <- DESeq2::DESeq(
    dds,
    quiet = TRUE,
    parallel = FALSE
  )

  expected_coef <- "state_IFN_vs_classical"

  if (!expected_coef %in% DESeq2::resultsNames(dds)) {
    stop(
      "Expected DESeq2 coefficient not found: ",
      expected_coef
    )
  }

  res <- DESeq2::lfcShrink(
    dds,
    coef = expected_coef,
    type = "apeglm",
    quiet = TRUE
  )

  res_df <- res |>
    as.data.frame() |>
    tibble::rownames_to_column("gene") |>
    dplyr::filter(
      !is.na(padj),
      padj < 0.05,
      !is.na(log2FoldChange)
    )

  loo_up <- res_df |>
    dplyr::filter(log2FoldChange > 0) |>
    dplyr::arrange(dplyr::desc(log2FoldChange)) |>
    dplyr::slice_head(n = top_n) |>
    dplyr::pull(gene)

  loo_dn <- res_df |>
    dplyr::filter(log2FoldChange < 0) |>
    dplyr::arrange(log2FoldChange) |>
    dplyr::slice_head(n = top_n) |>
    dplyr::pull(gene)

  stopifnot(
    length(loo_up) == top_n,
    length(loo_dn) == top_n,
    !anyDuplicated(loo_up),
    !anyDuplicated(loo_dn),
    length(intersect(loo_up, loo_dn)) == 0L
  )

  jaccard_up_value <- jaccard_similarity(loo_up, full_up)
  jaccard_dn_value <- jaccard_similarity(loo_dn, full_dn)

  list(
    dropped = drop_patient,
    n_sig = nrow(res_df),
    jaccard_up = jaccard_up_value,
    jaccard_dn = jaccard_dn_value,
    jaccard_mean = mean(c(jaccard_up_value, jaccard_dn_value)),
    loo_up = loo_up,
    loo_dn = loo_dn
  )
}


# -----------------------------------------------------------------------------
# Section 4 . Run all nine LOO iterations
# -----------------------------------------------------------------------------

all_patients_numeric <- sort(as.integer(unique(cell_meta$patient)))

expected_patients <- c(1L, 2L, 3L, 4L, 5L, 7L, 8L, 9L, 10L)

if (
  anyNA(all_patients_numeric) ||
  !identical(all_patients_numeric, expected_patients)
) {
  stop("Patient identifiers differ from the finalized nine-patient cohort.")
}

all_patients <- as.character(all_patients_numeric)

cat(
  "\nStarting leave-one-patient-out analysis: ",
  length(all_patients),
  " iterations.\n\n",
  sep = ""
)

loo_results <- setNames(
  vector("list", length(all_patients)),
  all_patients
)

for (pt in all_patients) {
  cat(sprintf("Dropping patient %2s ... ", pt))
  t0 <- proc.time()

  loo_results[[pt]] <- run_loo_deseq(
    drop_patient = pt,
    cell_meta = cell_meta,
    counts_mat = counts_mat,
    full_up = inph_signature$up,
    full_dn = inph_signature$down
  )

  elapsed <- round((proc.time() - t0)[["elapsed"]])

  cat(sprintf(
    "done (%ds) | significant genes: %d | mean Jaccard: %.3f\n",
    elapsed,
    loo_results[[pt]]$n_sig,
    loo_results[[pt]]$jaccard_mean
  ))
}


# -----------------------------------------------------------------------------
# Section 5 . Signature-level stability
# -----------------------------------------------------------------------------

loo_df <- dplyr::bind_rows(
  lapply(loo_results, function(x) {
    data.frame(
      dropped = as.character(x$dropped),
      n_sig = as.integer(x$n_sig),
      jaccard_up = as.numeric(x$jaccard_up),
      jaccard_dn = as.numeric(x$jaccard_dn),
      jaccard_mean = as.numeric(x$jaccard_mean),
      stringsAsFactors = FALSE
    )
  })
)

stopifnot(
  nrow(loo_df) == 9L,
  !anyDuplicated(loo_df$dropped)
)

mean_jaccard_up <- mean(loo_df$jaccard_up)
mean_jaccard_dn <- mean(loo_df$jaccard_dn)
overall_mean_jaccard <- mean(c(loo_df$jaccard_up, loo_df$jaccard_dn))

cat("\n=== Leave-One-Out Signature Stability ===\n")
print(loo_df)

cat(sprintf("\nMean Jaccard UP  : %.3f\n", mean_jaccard_up))
cat(sprintf("Mean Jaccard DOWN: %.3f\n", mean_jaccard_dn))
cat(sprintf("Min  Jaccard UP  : %.3f\n", min(loo_df$jaccard_up)))
cat(sprintf("Min  Jaccard DOWN: %.3f\n", min(loo_df$jaccard_dn)))
cat(sprintf("Overall mean     : %.3f\n", overall_mean_jaccard))

cat(sprintf(
  "\nPredefined stability criterion (overall mean >= 0.70): %s\n",
  ifelse(overall_mean_jaccard >= 0.70, "PASS", "FAIL")
))

# Locked manuscript-level result guard.
JACCARD_TOLERANCE <- 0.002

if (
  abs(mean_jaccard_up - 0.714) > JACCARD_TOLERANCE ||
  abs(mean_jaccard_dn - 0.733) > JACCARD_TOLERANCE ||
  abs(overall_mean_jaccard - 0.724) > JACCARD_TOLERANCE
) {
  stop(
    "LOO Jaccard summary differs from the finalized analysis beyond tolerance. ",
    "Expected approximately 0.714 UP, 0.733 DOWN, and 0.724 overall."
  )
}

loo_output_path <- file.path(
  PROCESSED_DIR,
  "loo_signature_stability.rds"
)

saveRDS(loo_df, loo_output_path)


# -----------------------------------------------------------------------------
# Section 6 . Persistence of original UP-signature genes
# -----------------------------------------------------------------------------

cat("\n=== UP-gene persistence ===\n")

all_loo_up <- unlist(
  lapply(loo_results, function(x) x$loo_up),
  use.names = FALSE
)

gene_counts_up <- table(all_loo_up)

persist_df <- data.frame(
  gene = names(gene_counts_up),
  n_iters = as.integer(gene_counts_up),
  stringsAsFactors = FALSE
) |>
  dplyr::mutate(
    in_sig = gene %in% inph_signature$up
  ) |>
  dplyr::arrange(
    dplyr::desc(n_iters),
    gene
  )

stopifnot(
  !anyDuplicated(persist_df$gene),
  all(persist_df$n_iters >= 1L),
  all(persist_df$n_iters <= 9L)
)

n_tracked <- sum(persist_df$in_sig)
n_stable <- sum(persist_df$n_iters == 9L & persist_df$in_sig)

if (
  n_tracked != 137L ||
  n_stable != 107L
) {
  stop(
    "UP-signature persistence differs from the finalized analysis: expected ",
    "137 original UP genes to re-enter at least one LOO top-150 list and ",
    "107 to persist in all nine iterations."
  )
}

cat(
  "Original UP genes appearing in >=1 LOO top-150 list: ",
  n_tracked,
  "\n",
  sep = ""
)

cat(
  "Original UP genes retained in all 9 iterations: ",
  n_stable,
  "\n",
  sep = ""
)

persistence_output_path <- file.path(
  PROCESSED_DIR,
  "loo_up_gene_persistence.csv"
)

readr::write_csv(
  persist_df,
  persistence_output_path
)


