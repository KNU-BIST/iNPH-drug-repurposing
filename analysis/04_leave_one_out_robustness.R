# =============================================================================
# Leave-one-out signature stability and UP-gene persistence
# Script: 04_leave_one_out_robustness.R
# =============================================================================
#
# Project
# -------
# Systems biology prioritizes drug candidates for interferon-activated
# monocytes in idiopathic normal pressure hydrocephalus
#
# Author
# ------
# Md. Masudul Haque
#
# Purpose
# -------
# Test whether the finalized iNPH IFN-activated monocyte signature is driven
# by any single patient.
#
# Analyses
# --------
# 1. Repeat paired pseudobulk differential expression after excluding each
#    patient in turn.
# 2. Reconstruct 150-UP/150-DOWN LOO signatures and calculate Jaccard
#    similarity to the full-data signature.
# 3. Track persistence of the original UP-signature genes across all nine
#    leave-one-patient-out iterations.
#
# Inputs
# ------
# data/processed/seu_monocyte_subclustered.rds
# data/processed/inph_ifn_signature.rds
#
# Outputs
# -------
# data/processed/loo_signature_stability.rds
# data/processed/loo_up_gene_persistence.csv
#
# Reproducibility notes
# ---------------------
# - Uses the canonical 22,197-cell monocyte object generated by Script 01.
# - The contrast is fixed to IFN-activated cluster 5 versus classical cluster 0.
# - Every LOO iteration retains a paired ~ patient + state DESeq2 design.
# - The full-analysis FDR and top-150 directional ranking rules are reapplied.
# =============================================================================


